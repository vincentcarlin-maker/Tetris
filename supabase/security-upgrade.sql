-- À exécuter d'abord sur une copie/staging, après sauvegarde.
-- Compatible avec les tables profiles(username, data, updated_at) de l'archive.
-- Les anciens profils restent sans user_id : aucun rattachement automatique.
begin;
create schema if not exists private;
revoke all on schema private from public, anon;
grant usage on schema private to authenticated;

create table if not exists public.profiles (
    username text primary key, data jsonb not null default '{}', updated_at timestamptz not null default now()
);
alter table public.profiles add column if not exists user_id uuid references auth.users(id) on delete cascade;
create unique index if not exists profiles_auth_user_id on public.profiles(user_id);
create table if not exists public.messages (
    id bigint generated by default as identity primary key,
    sender_id text not null, receiver_id text not null, text text not null,
    read boolean not null default false, created_at timestamptz not null default now()
);
create index if not exists messages_receiver_created on public.messages(receiver_id, created_at);
create index if not exists messages_sender_receiver on public.messages(sender_id, receiver_id);
create table if not exists public.transactions (
    id bigint generated by default as identity primary key, username text not null,
    type text not null, amount numeric not null, description text, game_id text,
    timestamp timestamptz not null default now()
);
create index if not exists transactions_username on public.transactions(username);

-- Remove legacy credentials; never import them into Auth.
update public.profiles set data = coalesce(data, '{}'::jsonb) - array['password','reset_code','reset_expiry','email'];

create or replace function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
    select coalesce((select auth.jwt())->'app_metadata'->>'role' = 'admin', false)
        and exists(select 1 from auth.users where id = (select auth.uid()));
$$;
create or replace function private.my_username() returns text
language sql stable security definer set search_path = '' as $$
    select username from public.profiles where user_id = (select auth.uid())
      and coalesce(data->>'banned', 'false') <> 'true';
$$;
revoke all on function private.is_admin(), private.my_username() from public, anon;
grant execute on function private.is_admin(), private.my_username() to authenticated;

-- Replace all legacy policies; permissive old policies must not remain OR'ed with these.
do $$ declare policy record; begin
    for policy in select schemaname, tablename, policyname from pg_policies
      where schemaname = 'public' and tablename in ('profiles','messages','transactions','public_profiles')
    loop execute format('drop policy %I on %I.%I', policy.policyname, policy.schemaname, policy.tablename); end loop;
end $$;
alter table public.profiles enable row level security;
alter table public.messages enable row level security;
alter table public.transactions enable row level security;
revoke all on public.profiles, public.messages, public.transactions from anon, authenticated;
grant select, insert, update, delete on public.profiles, public.messages to authenticated;
grant select, insert on public.transactions to authenticated;
-- Identity sequences on an existing installation may have different names.
do $$ declare seq text; begin
    foreach seq in array array[pg_get_serial_sequence('public.messages','id'), pg_get_serial_sequence('public.transactions','id')]
    loop if seq is not null then execute format('grant usage on sequence %s to authenticated', seq); end if; end loop;
end $$;
create policy profiles_select on public.profiles for select to authenticated
using (user_id = (select auth.uid()) or (select private.is_admin()));
create policy profiles_insert on public.profiles for insert to authenticated
with check ((user_id = (select auth.uid()) and username <> 'SYSTEM_CONFIG' and coalesce(data->>'banned','false') <> 'true' and not data ? 'role') or (select private.is_admin()));
create policy profiles_update on public.profiles for update to authenticated
using ((user_id = (select auth.uid()) and coalesce(data->>'banned','false') <> 'true') or (select private.is_admin()))
with check ((user_id = (select auth.uid()) and username <> 'SYSTEM_CONFIG' and coalesce(data->>'banned','false') <> 'true') or (select private.is_admin()));
create policy profiles_delete on public.profiles for delete to authenticated
using ((select private.is_admin()));

create or replace function private.guard_profile() returns trigger
language plpgsql set search_path = '' as $$
begin
    if new.data ?| array['password','reset_code','reset_expiry','email'] then
        raise exception 'Credentials and email belong in Auth';
    end if;
    if tg_op = 'UPDATE' and current_user in ('anon','authenticated') then
        if new.username is distinct from old.username or new.user_id is distinct from old.user_id then
            raise exception 'Profile identity is immutable';
        end if;
        if not private.is_admin() and
          (new.data->'role' is distinct from old.data->'role' or new.data->'banned' is distinct from old.data->'banned') then
            raise exception 'Only an administrator can change account status';
        end if;
    end if;
    new.updated_at := now();
    return new;
end $$;
drop trigger if exists guard_profile on public.profiles;
create trigger guard_profile before insert or update on public.profiles for each row execute function private.guard_profile();
revoke all on function private.guard_profile() from public, anon, authenticated;

-- Public system configuration contains no private profile or transaction data.
create table if not exists public.app_config (id integer primary key check(id=1), data jsonb not null default '{}');
alter table public.app_config enable row level security;
revoke all on public.app_config from anon, authenticated;
grant select on public.app_config to anon, authenticated;
drop policy if exists config_read on public.app_config;
create policy config_read on public.app_config for select to anon, authenticated using (true);
create or replace function private.publish_config() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    if new.username = 'SYSTEM_CONFIG' then
        insert into public.app_config(id,data) values(1,jsonb_build_object('disabledGames',new.data->'disabledGames','featureFlags',new.data->'featureFlags','neonSeekConfig',new.data->'neonSeekConfig'))
        on conflict(id) do update set data=excluded.data;
    end if;
    return new;
end $$;
revoke all on function private.publish_config() from public, anon, authenticated;
drop trigger if exists publish_config on public.profiles;
create trigger publish_config after insert or update on public.profiles for each row execute function private.publish_config();
insert into public.app_config(id,data)
select 1,jsonb_build_object('disabledGames',data->'disabledGames','featureFlags',data->'featureFlags','neonSeekConfig',data->'neonSeekConfig')
from public.profiles where username='SYSTEM_CONFIG'
on conflict(id) do update set data=excluded.data;

-- Public directory is a separate projection; private JSON never becomes readable to everyone.
create table if not exists public.public_profiles (
    username text primary key references public.profiles(username) on delete cascade,
    data jsonb not null default '{}', updated_at timestamptz not null default now()
);
alter table public.public_profiles enable row level security;
revoke all on public.public_profiles from anon, authenticated;
grant select on public.public_profiles to anon, authenticated;
create policy public_directory on public.public_profiles for select to anon, authenticated using (true);
create or replace function private.publish_profile() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
    if new.username <> 'SYSTEM_CONFIG' then
        insert into public.public_profiles(username, data, updated_at)
        values(new.username, jsonb_build_object('avatarId',new.data->'avatarId','frameId',new.data->'frameId','highScores',new.data->'highScores'),new.updated_at)
        on conflict(username) do update set data=excluded.data, updated_at=excluded.updated_at;
    end if;
    return new;
end $$;
revoke all on function private.publish_profile() from public, anon, authenticated;
drop trigger if exists publish_profile on public.profiles;
create trigger publish_profile after insert or update on public.profiles for each row execute function private.publish_profile();
insert into public.public_profiles(username,data,updated_at)
select username,jsonb_build_object('avatarId',data->'avatarId','frameId',data->'frameId','highScores',data->'highScores'),updated_at
from public.profiles where username <> 'SYSTEM_CONFIG'
on conflict(username) do update set data=excluded.data,updated_at=excluded.updated_at;

create policy messages_select on public.messages for select to authenticated
using (sender_id = (select private.my_username()) or receiver_id = (select private.my_username()) or (select private.is_admin()));
create policy messages_insert on public.messages for insert to authenticated
with check (sender_id = (select private.my_username()) and not read and length(text) between 1 and 10000);
create policy messages_update on public.messages for update to authenticated
using (receiver_id = (select private.my_username())) with check (receiver_id = (select private.my_username()));
-- A receiver may mark a message read, but cannot rewrite its author or contents.
revoke update on public.messages from authenticated;
grant update(read) on public.messages to authenticated;
create policy messages_delete on public.messages for delete to authenticated
using (sender_id = (select private.my_username()) or receiver_id = (select private.my_username()) or (select private.is_admin()));
create policy transactions_select on public.transactions for select to authenticated
using (username = (select private.my_username()) or (select private.is_admin()));
create policy transactions_insert on public.transactions for insert to authenticated
with check ((username = (select private.my_username()) and type in ('EARN','PURCHASE')) or (select private.is_admin()));

create or replace function public.save_my_profile(p_username text, p_patch jsonb) returns void
language plpgsql security invoker set search_path = '' as $$
begin
    if jsonb_typeof(p_patch) <> 'object' then raise exception 'Invalid profile'; end if;
    if p_patch ?| array['password','reset_code','reset_expiry','email'] then raise exception 'Use Auth to change credentials'; end if;
    if p_username = 'SYSTEM_CONFIG' and private.is_admin() then
        insert into public.profiles(username,data) values(p_username,p_patch)
        on conflict(username) do update set data=public.profiles.data || excluded.data;
    else
        update public.profiles set data=data || p_patch where username=p_username;
        if not found then raise exception 'Profile not found or access denied'; end if;
    end if;
end $$;
revoke all on function public.save_my_profile(text,jsonb) from public, anon;
grant execute on function public.save_my_profile(text,jsonb) to authenticated;

-- Privileged friendship code is private, checks the authenticated receiver and request,
-- and locks both profiles in a deterministic order before changing either side.
create or replace function private.accept_friend_request(p_requester text) returns void
language plpgsql security definer set search_path = '' as $$
declare me text; mine jsonb; theirs jsonb;
begin
    me := private.my_username();
    if me is null or me = p_requester then raise exception 'Access denied'; end if;
    perform 1 from public.profiles where username in (me,p_requester) order by username for update;
    if not exists(select 1 from public.messages where sender_id=p_requester and receiver_id=me and text='CMD:FRIEND_REQUEST') then
        raise exception 'Friend request not found';
    end if;
    select data into mine from public.profiles where username=me;
    select data into theirs from public.profiles where username=p_requester;
    if mine is null or theirs is null then raise exception 'Profile not found'; end if;
    if not exists(select 1 from jsonb_array_elements(coalesce(mine->'friends','[]')) f where f->>'name'=p_requester) then
        update public.profiles set data=jsonb_set(data,'{friends}',coalesce(data->'friends','[]') || jsonb_build_array(jsonb_build_object('id',p_requester,'name',p_requester,'avatarId',theirs->>'avatarId','frameId',theirs->>'frameId','status','offline'))) where username=me;
    end if;
    if not exists(select 1 from jsonb_array_elements(coalesce(theirs->'friends','[]')) f where f->>'name'=me) then
        update public.profiles set data=jsonb_set(data,'{friends}',coalesce(data->'friends','[]') || jsonb_build_array(jsonb_build_object('id',me,'name',me,'avatarId',mine->>'avatarId','frameId',mine->>'frameId','status','offline'))) where username=p_requester;
    end if;
    delete from public.messages where sender_id=p_requester and receiver_id=me and text='CMD:FRIEND_REQUEST';
end $$;
revoke all on function private.accept_friend_request(text) from public, anon;
grant execute on function private.accept_friend_request(text) to authenticated;
create or replace function public.accept_friend_request(p_requester text) returns void
language sql security invoker set search_path = '' as $$ select private.accept_friend_request(p_requester); $$;
revoke all on function public.accept_friend_request(text) from public, anon;
grant execute on function public.accept_friend_request(text) to authenticated;

create or replace function private.delete_my_account(p_username text) returns void
language plpgsql security definer set search_path = '' as $$
declare uid uuid := auth.uid();
begin
    if uid is null or not exists(select 1 from public.profiles where user_id=uid and username=p_username) then raise exception 'Access denied'; end if;
    delete from public.messages where sender_id=p_username or receiver_id=p_username;
    delete from public.transactions where username=p_username;
    delete from auth.sessions where user_id=uid;
    delete from public.profiles where user_id=uid;
    delete from auth.users where id=uid;
end $$;
revoke all on function private.delete_my_account(text) from public, anon;
grant execute on function private.delete_my_account(text) to authenticated;
create or replace function public.delete_my_account(p_username text) returns void
language sql security invoker set search_path = '' as $$ select private.delete_my_account(p_username); $$;
revoke all on function public.delete_my_account(text) from public, anon;
grant execute on function public.delete_my_account(text) to authenticated;
-- Disable the legacy RPC if present: its implementation was not included in the archive.
do $$ declare f record; begin
  for f in select oid::regprocedure signature from pg_proc where pronamespace='public'::regnamespace and proname='search_users_by_name'
  loop execute format('revoke all on function %s from public, anon, authenticated', f.signature); end loop;
end $$;
commit;
